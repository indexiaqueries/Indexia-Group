let totalUpdated = 0;

for (const [lang, spotlightData] of Object.entries(spotlightTranslations)) {
  const filePath = resolve(localesDir, `${lang}.json`);
  const data = JSON.parse(readFileSync(filePath, "utf8"));

  if (!data.spotlight) data.spotlight = {};

  let changed = 0;
  for (const [company, content] of Object.entries(spotlightData)) {
    if (!data.spotlight[company]) data.spotlight[company] = {};

    for (const [key, val] of Object.entries(content)) {
      const current = JSON.stringify(data.spotlight[company][key]);
      const newVal = JSON.stringify(val);
      if (current !== newVal) {
        data.spotlight[company][key] = val;
        changed++;
      }
    }
  }

  if (changed > 0) {
    writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
    console.log(`${lang}: ${changed} spotlight strings translated`);
    totalUpdated += changed;
  }
}

console.log(`\nDone. ${totalUpdated} total spotlight strings translated.`);
